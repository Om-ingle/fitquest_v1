# ─────────────────────────────────────────────────────────────────────────────
# Normalization & helpers
# ─────────────────────────────────────────────────────────────────────────────


def _normalize_row(raw: dict) -> dict:
    """Coerce one raw row (dict of ints or CSV strings) into typed values."""
    missing = [c for c in generator.COLUMNS if c not in raw]
    if missing:
        raise ValueError(f"raw row is missing columns: {missing}")
    row = dict(raw)
    for field in _INT_FIELDS:
        row[field] = int(row[field])
    return row


def _window(values: list, i: int, size: int) -> list:
    """Trailing inclusive window: values[max(0, i-size+1) .. i]."""
    return values[max(0, i - size + 1) : i + 1]


def _mean(values: list) -> float:
    return sum(values) / len(values)


def _f6(value: float) -> float:
    """Round floats to 6 decimals for tidy, deterministic CSV output."""
    return round(float(value), 6)


def _days_since_active(steps: list[int], i: int) -> int:
    """Days elapsed since the most recent active day (see manifest)."""
    if steps[i] >= STREAK_MIN_STEPS:
        return 0
    j = i - 1
    while j >= 0 and steps[j] < STREAK_MIN_STEPS:
        j -= 1
    return i - j  # j == -1 -> never active -> i + 1


# ─────────────────────────────────────────────────────────────────────────────
# Feature construction
# ─────────────────────────────────────────────────────────────────────────────


def _build_user_features(user_id: str, user_rows: list[dict]) -> list[dict]:
    """Build one user's ML-ready rows from their day-sorted raw rows."""
    steps = [r["steps"] for r in user_rows]
    minutes = [r["active_minutes"] for r in user_rows]
    captured = [r["hexes_captured"] for r in user_rows]
    lost = [r["hexes_lost"] for r in user_rows]
    owned = [r["hexes_owned"] for r in user_rows]
    defense = [r["defense_steps"] for r in user_rows]
    goals_done = [r["goal_completed"] for r in user_rows]

    out: list[dict] = []
    for i, row in enumerate(user_rows):
        w7_steps = _window(steps, i, 7)
        w7_steps_sum = sum(w7_steps)
        prior7 = steps[max(0, i - 7) : i]  # previous 7 days, excluding D

        out.append(
            {
                # metadata (never features)
                "synthetic_user_id": user_id,
                "day": row["day"],
                # activity
                "steps_today": steps[i],
                "active_minutes_today": minutes[i],
                "steps_3d_avg": _f6(_mean(_window(steps, i, 3))),
                "steps_7d_avg": _f6(_mean(w7_steps)),
                "active_minutes_3d_avg": _f6(_mean(_window(minutes, i, 3))),
                "active_minutes_7d_avg": _f6(_mean(_window(minutes, i, 7))),
                "activity_days_7d": sum(
                    1 for s in w7_steps if s >= STREAK_MIN_STEPS
                ),
                "steps_change_vs_7d_avg": (
                    _f6(steps[i] - _mean(prior7)) if prior7 else 0.0
                ),
                # consistency
                "current_streak": row["streak"],
                "goal_completion_rate_7d": _f6(_mean(_window(goals_done, i, 7))),
                "days_since_active": _days_since_active(steps, i),
                # territory (as of end of day D)
                "hexes_owned": owned[i],
                "captures_7d": sum(_window(captured, i, 7)),
                "losses_7d": sum(_window(lost, i, 7)),
                "territory_change_7d": owned[i] - (owned[i - 7] if i >= 7 else 0),
                "defense_steps_7d": sum(_window(defense, i, 7)),
                "defense_ratio_7d": (
                    _f6(sum(_window(defense, i, 7)) / w7_steps_sum)
                    if w7_steps_sum
                    else 0.0
                ),
                # goals
                "goal_steps": row["goal_steps"],
                "goal_completed_today": goals_done[i],
                # derived extras
                "active_today": 1 if steps[i] >= STREAK_MIN_STEPS else 0,
                "goal_progress_ratio": (
                    _f6(steps[i] / row["goal_steps"]) if row["goal_steps"] else 0.0
                ),
                # provenance (never a feature)
                "data_source": row.get("data_source", DATA_SOURCE),
            }
        )
    return out


def build_features(raw_rows: list[dict]) -> list[dict]:
    """Transform raw daily rows (generator output or reread CSV) into
    ML-ready feature rows — one per (user, day), in input user order with
    each user's days ascending.

    Pure function: no I/O, stdlib only, deterministic for identical input.
    """
    if not raw_rows:
        raise ValueError("cannot build features from an empty dataset")

    rows = [_normalize_row(r) for r in raw_rows]
    grouped: dict[str, list[dict]] = {}
    for row in rows:
        grouped.setdefault(row["synthetic_user_id"], []).append(row)

    out: list[dict] = []
    for user_id, user_rows in grouped.items():
        user_rows.sort(key=lambda r: r["day"])  # defensive; input is ordered
        out.extend(_build_user_features(user_id, user_rows))
    return out


# ─────────────────────────────────────────────────────────────────────────────
# I/O
# ─────────────────────────────────────────────────────────────────────────────


def write_features(rows: list[dict], output_path: str | Path) -> Path:
    """Write feature rows to CSV in canonical column order. Returns the path."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=OUTPUT_COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    return path


def read_features(input_path: str | Path) -> list[dict]:
    """Read a feature CSV back into row dicts (values as strings)."""
    path = Path(input_path)
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def write_manifest(output_path: str | Path, source_path: str | Path | None = None) -> Path:
    """Write the machine-readable feature manifest (JSON) for reproducibility."""
    doc = {
        "dataset": (
            "FitQuest synthetic fitness ML-ready features — SYNTHETIC data, "
            "not real user data; demonstrates pipeline feasibility only and "
            "establishes no real-world predictive performance."
        ),
        "generated_from": str(source_path) if source_path else None,
        "n_model_features": len(MODEL_FEATURES),
        "model_features": MODEL_FEATURES,
        "metadata_columns": METADATA_COLUMNS + ["data_source"],
        "leakage_policy": (
            "Every feature is computed only from the sample's own day D and "
            "earlier days of the SAME user; trailing windows are inclusive of "
            "D and expand at history start; no future rows and no cross-user "
            "data contribute to any feature."
        ),
        "target": (
            "None by design — Phase 4B.3 decides the learning target; the "
            "rules engine's recommendation labels are deliberately NOT used "
            "as ground truth."
        ),
        "features": FEATURE_MANIFEST,
    }
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(doc, handle, indent=2)
        handle.write("\n")
    return path


# ─────────────────────────────────────────────────────────────────────────────
# CLI
# ─────────────────────────────────────────────────────────────────────────────


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="synthetic_features",
        description=(
            "Build ML-ready features from the SYNTHETIC fitness dataset "
            "(never present them as real user data)."
        ),
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=DEFAULT_INPUT,
        help="raw daily dataset CSV (generator output)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="ML-ready feature CSV path",
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=DEFAULT_MANIFEST,
        help="machine-readable feature manifest JSON path",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _build_arg_parser().parse_args(argv)

    raw_rows = generator.read_dataset(args.input)
    features = build_features(raw_rows)
    out_path = write_features(features, args.output)
    manifest_path = write_manifest(args.manifest, source_path=args.input)

    n_users = len({row["synthetic_user_id"] for row in features})
    print(f"Read {len(raw_rows)} raw rows from {args.input}")
    print(
        f"Wrote {len(features)} ML-ready rows ({n_users} users, "
        f"{len(MODEL_FEATURES)} model features) to {out_path}"
    )
    print(f"Wrote feature manifest to {manifest_path}")
    print(f"rows are data_source={DATA_SOURCE!r} | no ML target defined (Phase 4B.3)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
