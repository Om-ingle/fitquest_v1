"""Feature engineering: raw synthetic daily activity -> ML-ready samples.

⚠  IMPORTANT — the input dataset and every feature derived here are SYNTHETIC.
   - They are generated by ``generator.py`` (``data_source="synthetic"``) and
     are NOT real FitQuest user data.
   - This pipeline demonstrates *feasibility of the ML data path only*. It
     does NOT establish any real-world predictive performance.
   - Real FitQuest telemetry will eventually replace/augment the synthetic
     dataset; the schema here is designed so real rows can flow through the
     same code under a different ``data_source`` label.

Semantics (leakage policy):
    Every feature describes one user *as of the end of day D* and is computed
    ONLY from that user's days D and earlier. No future row (D+1, D+2, ...)
    ever contributes to a feature value for day D, and users never share
    history. Rolling windows are *trailing and inclusive of today*, and they
    EXPAND at the start of a user's history (a 7-day average on the user's
    very first day is just that day's value) so no early rows are dropped.

No ML target is defined here. Phase 4B.3 will decide the learning target;
deliberately *not* labeling rows with the rules engine's recommendation
outcomes, which would mostly teach a model to replay the existing rules.
"""

